"""
Evaluation harness for the agent's actual answer quality.

This is intentionally separate from tests/test_agent.py. That file proves the
self-correction *machinery* works (retries happen, destructive SQL never
runs) using a scripted fake LLM and costs nothing to run. This file asks
whether the real LLM, given a real question, generates SQL that returns the
*correct* answer -- which is a completely different kind of failure than a
syntax error, and needs a real model to test at all.

This is a script, not a pytest suite, on purpose: it calls the live Gemini
API, costs a handful of real tokens per run, and shouldn't run automatically
on every `pytest` invocation or in CI alongside the free unit tests.

Usage:
    python -m tests.eval_questions

Expected answers below were computed directly against the real dataset
(see the queries used to derive them in the project history / README) --
they are NOT generated by the agent, so they're a real check, not the agent
grading its own homework.
"""

from src.agent import ask
from src.db import get_engine

# Each case: the question to ask in plain English, and a validator that checks
# the agent's actual (columns, rows) against the known-correct answer computed
# independently from the real data.
EVAL_CASES = [
    {
        "question": "How many active employees are there?",
        "validate": lambda cols, rows: rows == [[352]],
        "expected": "352",
    },
    {
        "question": "How many employees work in the Sales department?",
        "validate": lambda cols, rows: rows == [[178]],
        "expected": "178",
    },
    {
        "question": "How many employees have an Excellent performance rating?",
        "validate": lambda cols, rows: rows == [[267]],
        "expected": "267",
    },
    {
        "question": "Which department has the highest average salary?",
        "validate": lambda cols, rows: len(rows) > 0 and rows[0][0] == "Sales",
        "expected": "Sales (avg ~86896.68)",
    },
    {
        "question": "How many active employees work remotely?",
        "validate": lambda cols, rows: rows == [[185]],
        "expected": "185",
    },
    {
        "question": "Which region has the most employees?",
        "validate": lambda cols, rows: len(rows) > 0 and rows[0][0] == "California",
        "expected": "California (187 employees)",
    },
]


def run_eval() -> None:
    engine = get_engine("AGENT_DATABASE_URL")
    passed = 0

    for i, case in enumerate(EVAL_CASES, start=1):
        result = ask(engine, case["question"])
        print(f"\n[{i}/{len(EVAL_CASES)}] {case['question']}")
        print(f"  SQL ({result.attempts} attempt(s)): {result.sql}")

        if not result.succeeded:
            print(f"  FAIL -- agent could not execute any SQL. Error: {result.error}")
            continue

        ok = case["validate"](result.columns, result.rows)
        print(f"  Got: {result.rows} | Expected: {case['expected']}")
        print("  PASS" if ok else "  FAIL -- result did not match expected answer")
        passed += int(ok)

    print(f"\n{'=' * 40}\n{passed}/{len(EVAL_CASES)} passed\n{'=' * 40}")


if __name__ == "__main__":
    run_eval()
